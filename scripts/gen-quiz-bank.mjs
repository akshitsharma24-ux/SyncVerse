// Generates server/quiz/expected.ts: the expected output of every hidden test of every coding problem, by running the problem's model
// solution (Python). The hand-written sample outputs are an independent check: a model solution that disagrees with one stops the run.
//   node scripts/gen-quiz-bank.mjs            write the file
//   node scripts/gen-quiz-bank.mjs --check    only verify the file is up to date (used by verify:quiz)
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { tsImport } from 'tsx/esm/api';

const check = process.argv.includes('--check');
const python = process.env.PYTHON_BIN ?? (process.platform === 'win32' ? 'python' : 'python3');
const { PROBLEMS_A } = await tsImport('../server/quiz/problems-a.ts', import.meta.url);
const { PROBLEMS_B } = await tsImport('../server/quiz/problems-b.ts', import.meta.url);
const { PROBLEMS_C } = await tsImport('../server/quiz/problems-c.ts', import.meta.url);
const problems = [...PROBLEMS_A, ...PROBLEMS_B, ...PROBLEMS_C];

const tokens = (s) => s.replace(/\r\n/g, '\n').split(/\s+/).filter(Boolean);
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sv-quiz-'));

function runReference(problem, input) {
  const file = path.join(dir, `${problem.id}.py`);
  fs.writeFileSync(file, problem.reference, 'utf8');
  const r = spawnSync(python, ['-X', 'utf8', '-I', file], { input, encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024 });
  if (r.error || r.status !== 0) throw new Error(`${problem.id}: the model solution failed: ${r.error?.message ?? r.stderr.trim().split('\n').pop()}`);
  return r.stdout.replace(/\r\n/g, '\n').trim();
}

const expected = {};
let failed = 0;
for (const p of problems) {
  try {
    for (const [i, s] of p.samples.entries()) {
      const got = runReference(p, s.input);
      if (tokens(got).join(' ') !== tokens(s.output).join(' ')) throw new Error(`${p.id}: sample ${i + 1} expects ${JSON.stringify(s.output)} but the model solution prints ${JSON.stringify(got)}`);
    }
    expected[p.id] = p.hidden.map((h) => runReference(p, typeof h === 'function' ? h() : h));
    const empty = expected[p.id].findIndex((o) => !o);
    if (empty >= 0) throw new Error(`${p.id}: hidden test ${empty + 1} produced no output`);
  } catch (e) {
    failed++;
    console.log('FAIL ', e.message);
  }
}
fs.rmSync(dir, { recursive: true, force: true });

const body = `/** Generated by scripts/gen-quiz-bank.mjs from the model solutions. Do not edit by hand: run \`npm run gen:quiz\`. */
export const EXPECTED: Record<string, string[]> = ${JSON.stringify(expected, null, 2)};
`;
const target = path.resolve('server/quiz/expected.ts');
if (failed) process.exit(1);
if (check) {
  const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') === body;
  console.log(same ? `expected.ts is up to date (${problems.length} problems)` : 'FAIL  expected.ts is out of date: run npm run gen:quiz');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, body, 'utf8');
console.log(`wrote server/quiz/expected.ts: ${problems.length} problems, ${Object.values(expected).reduce((n, a) => n + a.length, 0)} hidden tests`);
